/**
 * Regenerates src/generated/*:
 *
 *   obsidian-app.ts   Obsidian's app.css (vendor/obsidian-app.css), converted.
 *                     Bundled so sites never need Obsidian. Update the vendored
 *                     file when Obsidian ships CSS changes, then rerun.
 *   lucide.ts         Every Lucide icon (current + legacy names, which Obsidian
 *                     themes still use) as compact SVG bodies, for resolving
 *                     `--callout-icon: lucide-…`.
 *   legacy-themes.ts  Pre-3.0 theme ids (`tokyo-night`, `catppuccin.frappe`) →
 *                     Obsidian theme name + the Style Settings preset the old
 *                     packages were built with. Only regenerated when
 *                     --legacy=<quartz-themes repo> is given.
 *
 *   npx tsx scripts/generate.ts [--legacy=../../../quartz-themes]
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as lucide from "@lucide/icons";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src/generated");
fs.mkdirSync(out, { recursive: true });
const arg = (k: string) =>
  process.argv.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3);
const banner =
  "// AUTO-GENERATED by scripts/generate.ts — do not edit.\n/* eslint-disable */\n";

// ---- lucide -----------------------------------------------------------------
type Node = [string, Record<string, string | number>, Node[]?];
const render = (nodes: Node[]): string =>
  nodes
    .map(([tag, attrs, children]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}='${v}'`)
        .join(" ");
      return children?.length
        ? `<${tag} ${a}>${render(children)}</${tag}>`
        : `<${tag} ${a}/>`;
    })
    .join("");
const kebab = (s: string) =>
  s
    .replace(/Icon$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-zA-Z])([0-9])/g, "$1-$2")
    .toLowerCase();
const bodies: Record<string, string> = {};
const aliases: Record<string, string> = {};
for (const [exportName, icon] of Object.entries(
  lucide as Record<string, unknown>,
)) {
  const data = icon as { name?: string; node?: Node[] };
  if (!data?.name || !Array.isArray(data.node)) continue;
  bodies[data.name] ??= render(data.node);
  if (exportName.startsWith("Lucide")) continue;
  const alt = kebab(exportName);
  if (alt !== data.name) aliases[alt] ??= data.name;
}
for (const k of Object.keys(aliases)) if (bodies[k]) delete aliases[k];
fs.writeFileSync(
  path.join(out, "lucide.ts"),
  banner +
    `/** Lucide icon name → inner SVG markup (24×24 grid, stroke=currentColor). */\n` +
    `export const LUCIDE: Record<string, string> = ${JSON.stringify(bodies)};\n` +
    `/** Legacy / alternative names → current name. */\n` +
    `export const LUCIDE_ALIASES: Record<string, string> = ${JSON.stringify(aliases)};\n`,
);
console.log(
  `lucide: ${Object.keys(bodies).length} icons, ${Object.keys(aliases).length} aliases`,
);

// ---- obsidian app.css -----------------------------------------------------
// Imported after lucide.ts exists, since the converter's icon resolver uses it.
const { convertObsidianCss } = await import("../src/convert/convert");
const { resolveIcon } = await import("../src/convert/icons");
const appFile = path.join(root, "vendor/obsidian-app.css");
const appCss = fs.readFileSync(appFile, "utf8");
// Obsidian's app.css loads fonts shipped inside the app (`public/InterVariable.woff2`).
// Those paths don't exist on a Quartz site; drop such @font-face rules so the
// font stacks fall back (to a locally installed Inter, else the system UI font).
const postcss = (await import("postcss")).default;
const appRoot = postcss.parse(appCss);
let droppedFonts = 0;
appRoot.walkAtRules(/^font-face$/i, (at) => {
  const src = at.nodes?.find((n) => n.type === "decl" && n.prop === "src");
  const value = src && src.type === "decl" ? src.value : "";
  if (/url\(\s*["']?(?!data:|https?:)/i.test(value)) {
    at.remove();
    droppedFonts++;
  }
});
const app = convertObsidianCss(appRoot.toString(), {
  resolveIcon,
  filename: "app.css",
});
console.log(
  `app.css: dropped ${droppedFonts} @font-face rules pointing at Obsidian's bundled files`,
);
const sha = crypto
  .createHash("sha256")
  .update(appCss)
  .digest("hex")
  .slice(0, 16);
fs.writeFileSync(
  path.join(out, "obsidian-app.ts"),
  banner +
    `/** Obsidian's app.css converted for Quartz (source sha256 ${sha}). */\n` +
    `export const OBSIDIAN_APP = ${JSON.stringify({ sha, css: app.css, quarantine: app.quarantine })};\n`,
);
console.log(
  `app.css: ${app.stats.rules} rules → ${(app.css.length / 1024).toFixed(0)} KB (+${app.stats.quarantined} quarantined, ${app.stats.iconsResolved} icons)`,
);

// ---- legacy theme ids -----------------------------------------------------
const legacyRepo = arg("legacy");
if (legacyRepo) {
  const repo = path.resolve(legacyRepo);
  const themes = JSON.parse(
    fs.readFileSync(path.join(repo, "themes.json"), "utf8"),
  ).themes as Record<
    string,
    { modes?: string[]; style_settings?: Record<string, unknown> }
  >;
  const slugs = (raw: string) => {
    const s = raw
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/['’]/g, "")
      .toLowerCase();
    return [
      s.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
      s.replace(/[^a-z0-9_]+/g, "-").replace(/^-|-$/g, ""),
      s.replace(/[^a-z0-9]+/g, ""),
    ];
  };
  const names = new Map<string, string>();
  const vaultThemes = path.join(repo, "runner/vault/.obsidian/themes");
  for (const dir of fs.readdirSync(vaultThemes)) {
    let name = dir;
    try {
      name =
        JSON.parse(
          fs.readFileSync(path.join(vaultThemes, dir, "manifest.json"), "utf8"),
        ).name ?? dir;
    } catch {
      /* no manifest */
    }
    for (const s of [...slugs(dir), ...slugs(name)])
      if (!names.has(s)) names.set(s, name);
  }
  const legacy: Record<
    string,
    { name: string; modes?: string[]; styleSettings?: Record<string, unknown> }
  > = {};
  const unmatched: string[] = [];
  for (const [id, meta] of Object.entries(themes)) {
    if (id === "_baseline") continue;
    const base = id.split(".")[0]!;
    const name = names.get(base) ?? names.get(base.replace(/-/g, ""));
    if (!name) {
      unmatched.push(id);
      continue;
    }
    const preset = Object.fromEntries(
      Object.entries(meta.style_settings ?? {}).filter(([k]) =>
        k.includes("@@"),
      ),
    );
    legacy[id] = {
      name,
      ...(meta.modes ? { modes: meta.modes } : {}),
      ...(Object.keys(preset).length ? { styleSettings: preset } : {}),
    };
  }
  fs.writeFileSync(
    path.join(out, "legacy-themes.ts"),
    banner +
      `/** Pre-3.0 @quartz-themes ids → Obsidian theme name + Style Settings preset. */\n` +
      `export const LEGACY_THEMES: Record<string, { name: string; modes?: string[]; styleSettings?: Record<string, unknown> }> = ${JSON.stringify(legacy)};\n`,
  );
  console.log(
    `legacy: ${Object.keys(legacy).length} ids${unmatched.length ? `, unmatched: ${unmatched.join(", ")}` : ""}`,
  );
}
